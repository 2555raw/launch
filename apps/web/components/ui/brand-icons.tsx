export type SocialKind = 'website' | 'twitter' | 'discord' | 'telegram' | 'github';

export function SocialIcon({ kind, size = 16 }: { kind: SocialKind; size?: number }) {
  if (kind === 'discord') return <DiscordIcon size={size} />;
  if (kind === 'twitter') return <XIcon size={size} />;
  if (kind === 'telegram') return <TelegramIcon size={size} />;
  if (kind === 'github') return <GitHubIcon size={size} />;
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden>
      <circle cx="12" cy="12" r="10" />
      <path d="M2 12h20M12 2a15.3 15.3 0 0 1 4 10 15.3 15.3 0 0 1-4 10 15.3 15.3 0 0 1-4-10 15.3 15.3 0 0 1 4-10z" />
    </svg>
  );
}

const SOCIAL_COLORS: Record<SocialKind, string> = { website: 'hover:text-ember-300', twitter: 'hover:text-white', discord: 'hover:text-[#5865F2]', telegram: 'hover:text-[#26A5E4]', github: 'hover:text-white' };
const SOCIAL_LABELS: Record<SocialKind, string> = { website: 'Website', twitter: 'X', discord: 'Discord', telegram: 'Telegram', github: 'GitHub' };

/** Row of social links with brand logos; renders nothing for missing links. */
export function SocialLinks({ links, size = 16, labels = false, className = '' }: { links: Partial<Record<SocialKind, string | null | undefined>>; size?: number; labels?: boolean; className?: string }) {
  const entries = (Object.keys(SOCIAL_LABELS) as SocialKind[]).filter((k) => links[k]);
  if (entries.length === 0) return null;
  return (
    <div className={`flex flex-wrap items-center gap-2 ${className}`}>
      {entries.map((k) => (
        <a key={k} href={links[k] as string} target="_blank" rel="noopener noreferrer" title={SOCIAL_LABELS[k]} className={`inline-flex items-center gap-1.5 rounded-lg border border-white/10 bg-white/[0.04] px-2 py-1 text-xs text-slate-300 transition ${SOCIAL_COLORS[k]}`}>
          <SocialIcon kind={k} size={size} />
          {labels && <span>{SOCIAL_LABELS[k]}</span>}
        </a>
      ))}
    </div>
  );
}
