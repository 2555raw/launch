/* Turns forge's build output into the two files the rest of the project reads:
 *
 *   shared/artifacts.json         ABI + bytecode for every contract, so the deploy
 *                                 and verify scripts run without Foundry installed.
 *   web/src/generated/contracts.ts ABIs as `const` for viem's type inference, plus
 *                                 what the Verify page compares against: the
 *                                 runtime hash of the Coin implementation and the
 *                                 Launchpad runtime code with its immutable slots.
 *
 * Run after `forge build` (npm run contracts:build does both). */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { keccak256 } from 'viem';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const NAMES = ['Coin', 'TestCurrency', 'CurrencyDesk', 'Launchpad', 'Router'];

const artifacts = {};
for (const name of NAMES) {
  const raw = JSON.parse(readFileSync(join(root, 'contracts/out', `${name}.sol`, `${name}.json`), 'utf8'));
  const immutables = Object.values(raw.deployedBytecode.immutableReferences || {}).flat();
  artifacts[name] = {
    abi: raw.abi,
    bytecode: raw.bytecode.object,
    deployedBytecode: raw.deployedBytecode.object,
    immutables: immutables.map(({ start, length }) => [start, length]),
  };
}
writeFileSync(join(root, 'shared/artifacts.json'), JSON.stringify(artifacts));

const abi = (name) => JSON.stringify(artifacts[name].abi, null, 2);
const ts = `/* Generated by scripts/build-artifacts.mjs from the Foundry build. Do not edit. */

export const coinAbi = ${abi('Coin')} as const;

export const currencyAbi = ${abi('TestCurrency')} as const;

export const deskAbi = ${abi('CurrencyDesk')} as const;

export const launchpadAbi = ${abi('Launchpad')} as const;

export const routerAbi = ${abi('Router')} as const;

/** keccak256 of the Coin implementation's runtime code. It has no immutables, so
 *  it is identical on every deployment. */
export const COIN_RUNTIME_HASH = '${keccak256(artifacts.Coin.deployedBytecode)}' as const;

/** Launchpad runtime code and the byte ranges its immutables occupy; Verify masks
 *  those ranges before comparing, since they differ between deployments. */
export const LAUNCHPAD_RUNTIME = '${artifacts.Launchpad.deployedBytecode}' as const;
export const LAUNCHPAD_IMMUTABLES: ReadonlyArray<readonly [number, number]> = ${JSON.stringify(artifacts.Launchpad.immutables)};
`;
writeFileSync(join(root, 'web/src/generated/contracts.ts'), ts);
console.log('artifacts written:', NAMES.join(', '));
