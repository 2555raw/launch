await page.keyboard.press('e'); await page.waitForTimeout(700); await page.keyboard.press('e'); await page.waitForTimeout(800); await canvas().screenshot({ path: `${OUT}/mapa-canvas-90.png` })
await page.keyboard.press('e'); await page.waitForTimeout(700); await page.keyboard.press('e'); await page.waitForTimeout(800); await canvas().screenshot({ path: `${OUT}/mapa-canvas-180.png` })
await page.keyboard.press('e'); await page.waitForTimeout(700); await page.keyboard.press('e'); await page.waitForTimeout(800); await canvas().screenshot({ path: `${OUT}/mapa-canvas-270.png` })
await page.keyboard.press('e'); await page.waitForTimeout(700); await page.keyboard.press('e'); await page.waitForTimeout(800)
// zoom + selección + capa familia
const bb = await canvas().boundingBox()
await page.mouse.move(bb.x + bb.width * 0.5, bb.y + bb.height * 0.5)
for (let i = 0; i < 6; i++) { await page.mouse.wheel(0, -200); await page.waitForTimeout(60) }
await page.waitForTimeout(400)
const locs = await page.$$eval('[data-loc]', (els) => els.map((e) => e.dataset.loc))
const target = locs.find((l) => l.startsWith('L-A-01-03-'))
const tb = await page.locator(`[data-loc="${target}"]`).first().boundingBox()
await page.mouse.click(tb.x + tb.width / 2, tb.y + tb.height / 2); await page.waitForTimeout(500)
await page.screenshot({ path: `${OUT}/mapa-seleccion.png` })
await page.selectOption('select[aria-label="Capa de color"]', 'familia'); await page.waitForTimeout(400)
await canvas().screenshot({ path: `${OUT}/mapa-familia.png` })
await page.selectOption('select[aria-label="Capa de color"]', 'temperatura'); await page.waitForTimeout(400)
await canvas().screenshot({ path: `${OUT}/mapa-temperatura.png` })
await page.selectOption('select[aria-label="Capa de color"]', 'ocupacion'); await page.waitForTimeout(300)
// arrastrar y soltar (3D)
const all = await page.$$eval('[data-loc]', (els) => els.map((e) => ({ id: e.dataset.loc, title: e.querySelector('title')?.textContent ?? '' })))
const src = all.find((l) => l.id.startsWith('L-A-01-') && /Parcial/.test(l.title) && !/\/0 /.test(l.title))
const dst = all.find((l) => /Libre/.test(l.title) && /^L-A-02-\d\d-01$/.test(l.id))
const sb = await page.locator(`[data-loc="${src.id}"]`).first().boundingBox()
const db = await page.locator(`[data-loc="${dst.id}"]`).first().boundingBox()
await page.mouse.move(sb.x + sb.width / 2, sb.y + sb.height / 2); await page.mouse.down()
for (let i = 1; i <= 14; i++) { await page.mouse.move(sb.x + (db.x - sb.x) * (i / 14) + sb.width / 2, sb.y + (db.y - sb.y) * (i / 14) + sb.height / 2); await page.waitForTimeout(30) }
await page.waitForTimeout(200); await page.screenshot({ path: `${OUT}/mapa-arrastre.png` })
await page.mouse.up(); await page.waitForTimeout(500); await page.screenshot({ path: `${OUT}/mapa-confirmacion.png` })
await page.keyboard.press('Escape'); await page.waitForTimeout(300)
// pedidos
await go('pedidos'); await page.click('tbody tr >> nth=0'); await page.waitForTimeout(500); await page.screenshot({ path: `${OUT}/pedido.png` })
await page.keyboard.press('Escape')
// recepción detalle
await go('recepcion'); await page.click('tbody tr >> nth=0'); await page.waitForTimeout(400); await page.click('button:has-text("Iniciar recepción")'); await page.waitForTimeout(500); await page.screenshot({ path: `${OUT}/recepcion.png` })
await page.keyboard.press('Escape')
await go('expediciones'); await page.waitForTimeout(400); await page.screenshot({ path: `${OUT}/expediciones.png` })
await go('devoluciones'); await page.waitForTimeout(400); await page.screenshot({ path: `${OUT}/devoluciones.png` })
