await page.selectOption('select[aria-label="Puesto de trabajo"]', 'expedicion'); await go('dashboard'); await page.waitForTimeout(600); await page.screenshot({ path: `${OUT}/puesto-expedicion.png` })
await page.selectOption('select[aria-label="Puesto de trabajo"]', 'jefe'); await page.waitForTimeout(300)
// idiomas
await page.selectOption('header select >> nth=0', 'zh'); await go('dashboard'); await page.waitForTimeout(600); await page.screenshot({ path: `${OUT}/dashboard-zh.png` })
await page.selectOption('header select >> nth=0', 'en'); await go('mapa'); await page.waitForTimeout(900); await page.screenshot({ path: `${OUT}/mapa-en.png` })
await page.selectOption('header select >> nth=0', 'es')
