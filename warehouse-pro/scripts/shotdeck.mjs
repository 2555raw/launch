const OUT = '/tmp/claude-0/-home-user-launch/7610294d-d0c7-5499-a3e4-99de0c331e1f/scratchpad/deck2'
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox'] })
const ctx = await browser.newContext({ viewport: { width: 1600, height: 1000 }, deviceScaleFactor: 1.25 })
const page = await ctx.newPage()
const go = async (h) => { await page.goto('http://localhost:4173/#/' + h); await page.waitForTimeout(900) }
const canvas = () => page.locator('svg[role=application]')
await go('dashboard'); await page.waitForTimeout(600); await page.screenshot({ path: `${OUT}/dashboard.png` })
await go('mapa'); await page.waitForTimeout(800); await page.screenshot({ path: `${OUT}/mapa.png` })
